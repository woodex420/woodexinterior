import fs from 'node:fs';
import path from 'node:path';
import { listPages, listProjects, listInsights } from './content.js';

/**
 * Render the published site to static HTML so it can be uploaded to a plain
 * Apache/Hostinger account (no Node runtime required at the edge).
 *
 * The exporter boots the real Express app on an ephemeral port and crawls it,
 * which guarantees the static files are byte-identical to the dynamic site.
 */
export async function exportStatic(db, config, { targetDir = 'dist', log = () => {} } = {}) {
  const { createApp } = await import('../app.js');
  const target = path.resolve(targetDir);
  fs.mkdirSync(target, { recursive: true });

  const instance = createApp({ db, dbPath: ':memory:', ...pickOverrides(config) });
  const server = instance.app.listen(0, '127.0.0.1');
  await new Promise((resolve) => server.once('listening', resolve));
  const { port } = server.address();
  const base = `http://127.0.0.1:${port}`;

  const publishedPages = listPages(db, { status: 'published' });
  const projectSlugs = listProjects(db, { status: 'published', limit: 500 }).rows.map((p) => p.slug);
  const insightSlugs = listInsights(db, { status: 'published', limit: 500 }).rows.map((i) => i.slug);

  const routes = new Map();
  routes.set('/', 'index.html');
  routes.set('/portfolio', 'portfolio/index.html');
  routes.set('/insights', 'insights/index.html');
  routes.set('/services', 'services/index.html');
  routes.set('/contact', 'contact/index.html');
  routes.set('/thank-you', 'thank-you/index.html');
  routes.set('/search', 'search/index.html');
  routes.set('/404', '404.html');
  routes.set('/sitemap.xml', 'sitemap.xml');
  routes.set('/robots.txt', 'robots.txt');
  routes.set('/feed.xml', 'feed.xml');
  routes.set('/site.webmanifest', 'site.webmanifest');

  for (const page of publishedPages) {
    if (page.slug === 'home' || page.slug === '404') continue;
    if (['portfolio', 'insights', 'services', 'contact', 'thank-you'].includes(page.slug) && page.page_type !== 'legal') {
      // These have dedicated templates already registered above.
      if (page.page_type !== 'legal') continue;
    }
    routes.set(`/${page.slug}`, `${page.slug}/index.html`);
  }
  for (const slug of projectSlugs) routes.set(`/portfolio/${slug}`, `portfolio/${slug}/index.html`);
  for (const slug of insightSlugs) routes.set(`/insights/${slug}`, `insights/${slug}/index.html`);

  let files = 0;
  try {
    for (const [route, relFile] of routes) {
      const response = await fetch(`${base}${route}`, { redirect: 'manual' });
      if (response.status >= 400 && route !== '/404' && route !== '/search') {
        log(`skip ${route} (HTTP ${response.status})`);
        continue;
      }
      const body = await response.text();
      writeFile(path.join(target, relFile), body);
      files += 1;
    }
  } finally {
    await new Promise((resolve) => server.close(resolve));
    if (instance.db !== db) instance.db.close();
  }

  // Static assets: the design system is shared with the v1 site.
  const assetsTarget = path.join(target, 'assets');
  if (fs.existsSync(config.assetsDir)) {
    fs.mkdirSync(assetsTarget, { recursive: true });
    for (const file of fs.readdirSync(config.assetsDir)) {
      const src = path.join(config.assetsDir, file);
      if (fs.statSync(src).isFile()) {
        fs.copyFileSync(src, path.join(assetsTarget, file));
        files += 1;
      }
    }
  }
  // Uploaded media referenced by the CMS.
  const uploadsTarget = path.join(target, 'uploads');
  if (fs.existsSync(config.uploadDir)) {
    fs.mkdirSync(uploadsTarget, { recursive: true });
    for (const file of fs.readdirSync(config.uploadDir)) {
      const src = path.join(config.uploadDir, file);
      if (fs.statSync(src).isFile()) {
        fs.copyFileSync(src, path.join(uploadsTarget, file));
        files += 1;
      }
    }
  }
  writeFile(path.join(target, '.htaccess'), HTACCESS);
  writeFile(path.join(target, 'EXPORT-README.txt'), README_TEXT(new Date().toISOString()));

  return { target, pages: routes.size, files, exported_at: new Date().toISOString() };
}

function pickOverrides(config) {
  return {
    assetsDir: config.assetsDir,
    uploadDir: config.uploadDir,
    baseUrl: config.baseUrl,
    secureCookies: false,
    env: 'production',
  };
}

function writeFile(filePath, contents) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, contents);
}

const HTACCESS = `# Generated by Woodex OS — static export
DirectoryIndex index.html
ErrorDocument 404 /404.html
Options -Indexes

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css application/javascript application/json image/svg+xml
</IfModule>

<IfModule mod_expires.c>
  ExpiresActive On
  ExpiresByType text/html "access plus 1 hour"
  ExpiresByType text/css "access plus 1 month"
  ExpiresByType application/javascript "access plus 1 month"
  ExpiresByType image/jpeg "access plus 1 year"
  ExpiresByType image/png "access plus 1 year"
  ExpiresByType image/webp "access plus 1 year"
  ExpiresByType image/svg+xml "access plus 1 year"
  ExpiresByType font/woff2 "access plus 1 year"
</IfModule>

<IfModule mod_headers.c>
  Header set X-Content-Type-Options "nosniff"
  Header set X-Frame-Options "SAMEORIGIN"
  Header set Referrer-Policy "strict-origin-when-cross-origin"
  Header set Permissions-Policy "geolocation=(), microphone=(), camera=()"
  Header set Content-Security-Policy "default-src 'self'; img-src 'self' data:; style-src 'self' 'unsafe-inline'; script-src 'self'; font-src 'self'; form-action 'self'; frame-ancestors 'self'; object-src 'none'"
</IfModule>
`;

const README_TEXT = (stamp) => `WOODEX INTERIOR — STATIC EXPORT
Generated: ${stamp}

Upload the contents of this folder to your web root (public_html) on Hostinger.
The export mirrors the published content of Woodex OS: every published page,
project and insight, plus sitemap.xml, robots.txt and an RSS feed.

Notes
- URLs are directory-style (/about/ -> about/index.html). Keep DirectoryIndex enabled.
- Contact form submissions are static HTML only: point the form at your live OS
  deployment, or keep using the OS-hosted /contact endpoint.
- Re-export after content changes: Admin -> System -> Export, or \`npm run export\`.
`;
