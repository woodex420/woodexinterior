async function clickWire(scope, expression) {
    const target = scope.locator(`button[wire\\:click="${expression}"]`).first();
    const response = page.waitForResponse(r => new URL(r.url()).pathname.endsWith('/update') && r.request().method() === 'POST' && (r.request().postData() || '').includes(expression.split('(')[0]));
    await target.click();
    const received = await response;
    assert.equal(received.status(), 200);
    const body = await received.json();
    return body.components.map(c => JSON.parse(c.snapshot)).find(c => c.memo.name.includes('conversations.'))?.data;
}
